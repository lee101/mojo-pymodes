"""Regenerate src/tables.mojo from the installed upstream pyModeS.

Every table in src/tables.mojo is a verbatim copy of a table in pyModeS
3.6.0. This script exists so those copies are mechanically derived and
`tests/test_tables.py` can prove they still match upstream, rather than
being hand-typed and silently drifting.

    pixi run python build/gen_tables.py
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "src" / "tables.mojo"


def _upstream_root() -> Path:
    try:
        import pyModeS
    except ImportError:  # pragma: no cover - only outside the pixi env
        raise SystemExit("pyModeS is not importable; run this under `pixi run`")
    return Path(pyModeS.__file__).parent


SRC = _upstream_root()


def crc_table() -> list[int]:
    """pyModeS._bits._build_crc_table(), verbatim algorithm."""
    poly = 0xFFF409
    out = []
    for i in range(256):
        c = i << 16
        for _ in range(8):
            c = ((c << 1) ^ poly) if (c & 0x800000) else (c << 1)
        out.append(c & 0xFFFFFF)
    return out


def callsign_table() -> list[int]:
    """pyModeS._callsign._build_table(), as ordinals."""
    out = []
    for i in range(64):
        if 1 <= i <= 26:
            out.append(ord(chr(i | 0x40)))
        elif i == 32 or 48 <= i <= 57:
            out.append(ord(chr(i)))
        else:
            out.append(ord("#"))
    return out


def nl_boundaries() -> list[float]:
    text = (SRC / "position" / "_cpr.py").read_text()
    body = text.split("_NL_BOUNDARIES: tuple[float, ...] = (", 1)[1].split("\n)", 1)[0]
    body = re.sub(r"#[^\n]*", "", body)
    return [float(x) for x in body.replace("\n", " ").split(",") if x.strip()]


def nucp_table() -> list[int]:
    text = (SRC / "_uncertainty.py").read_text()
    body = text.split("TC_NUCp_lookup: dict[int, int] = {", 1)[1].split("}", 1)[0]
    d = {int(k): int(v) for k, v in re.findall(r"(\d+):\s*(\d+)", body)}
    # Upstream reads it as TC_NUCp_lookup.get(tc, 0), so a missing key is 0.
    return [d.get(tc, 0) for tc in range(32)]


def wake_vortex_table() -> list[int]:
    """Indices into `_WAKE_VORTEX_NAMES` (python/mojopymodes/decoder/bds/bds08.py).

    Laid out as tc * 8 + category for tc in 0..4, category in 0..7, so the
    Mojo side can index it with a shift and an OR and stay a straight
    transcription of the dict lookup.
    """
    text = (SRC / "decoder" / "bds" / "bds08.py").read_text()
    body = text.split("_WAKE_VORTEX: dict[tuple[int, int], str] = {", 1)[1].split("\n}", 1)[0]
    found = {
        (int(tc), int(cat)): name
        for tc, cat, name in re.findall(r'\((\d+),\s*(\d+)\):\s*"([^"]*)"', body)
    }
    names = list(_WAKE_VORTEX_NAMES)
    return [names.index(found.get((tc, cat), "No category information")) for tc in range(5) for cat in range(8)]


# Mirrors bds08._WAKE_VORTEX's own values, in the same order the dict is
# written, so `wake_vortex_table()` above can index it.
_WAKE_VORTEX_NAMES = [
    "Light",
    "Medium 1",
    "Medium 2",
    "High vortex aircraft",
    "Heavy",
    "High performance",
    "Rotorcraft",
    "Glider / sailplane",
    "Lighter-than-air",
    "Parachutist / skydiver",
    "Ultralight / hang-glider / paraglider",
    "Reserved",
    "UAV",
    "Space / transatmospheric vehicle",
    "Surface emergency vehicle",
    "Surface service vehicle",
    "Ground obstacle",
    "No category information",
]


def emit(name: str, values: list, mojo_type: str, per_line: int) -> str:
    lines = [f"comptime {name} = StaticTuple[{mojo_type}, {len(values)}]("]
    for k in range(0, len(values), per_line):
        lines.append("    " + ", ".join(str(v) for v in values[k : k + per_line]) + ",")
    lines.append(")")
    return "\n".join(lines)


def main() -> int:
    nl = nl_boundaries()
    wv = wake_vortex_table()
    assert len(nl) == 58, len(nl)
    assert len(wv) == 40, len(wv)
    body = "\n\n".join(
        [
            emit("_CRC_TABLE", crc_table(), "Int", 8),
            emit("_CALLSIGN_TABLE", callsign_table(), "UInt8", 16),
            emit("_NL_BOUNDARIES", nl, "Float64", 3),
            emit("TC_NUCp_lookup", nucp_table(), "Int", 32),
            emit("_WAKE_VORTEX", wv, "Int", 16),
        ]
    )
    OUT.write_text(
        '"""Static tables copied verbatim from pyModeS 3.6.0.\n\n'
        "Generated by build/gen_tables.py; do not edit by hand.\n"
        'tests/test_tables.py re-derives every entry from the installed\n'
        'upstream package and fails if any of them has drifted.\n"""\n\n'
        "from std.utils import StaticTuple\n\n\n" + body + "\n"
    )
    print(OUT)
    return 0


if __name__ == "__main__":
    sys.exit(main())
